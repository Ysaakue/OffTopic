// Generates lib/src/generated/voice_core_bindings.g.dart from
// include/voice_core.h.
//
// Run through tools/codegen.ps1 (Windows) so that the NDK LLVM directory is on
// PATH: libclang.dll depends on sibling DLLs in that directory.
//
// libclang comes from the Android NDK pinned in docs/DEPENDENCIES.md, so no
// separate LLVM install is needed on Windows. Override with LIBCLANG_PATH.
import 'dart:io';

import 'package:ffigen/ffigen.dart';

const _ndkVersion = '30.0.16248370';

/// Every public symbol of the C API starts with this prefix.
const _apiPrefix = 'vc_';

bool _isApi(String originalName) => originalName.startsWith(_apiPrefix);

Future<void> main() async {
  final packageRoot = Platform.script.resolve('../');
  final header = packageRoot.resolve('include/voice_core.h');

  final generator = FfiGenerator(
    input: Input(
      entryPoints: [header],
      include: (uri) => uri.path.endsWith('voice_core.h'),
    ),
    // Top-level declarations are excluded by default; keep only the C API.
    visitors: [
      Visitor(
        func: (node) => node.isIncluded = _isApi(node.originalName),
        struct: (node) => node.isIncluded = _isApi(node.originalName),
        enumClass: (node) => node.isIncluded = _isApi(node.originalName),
      ),
    ],
    output: Output(
      dart: DartOutput(
        path: packageRoot.resolve(
          'lib/src/generated/voice_core_bindings.g.dart',
        ),
      ),
      preamble:
          '// Generated by tool/ffigen.dart. Do not edit by hand.\n'
          '// ignore_for_file: type=lint',
      style: const DynamicLibraryBindings(
        wrapperName: 'VoiceCoreBindings',
        wrapperDocComment: 'Raw bindings to include/voice_core.h.',
      ),
    ),
  );

  await generator.generate(libclangDylib: _libclang());
}

Uri? _libclang() {
  final override = Platform.environment['LIBCLANG_PATH'];
  if (override != null && override.isNotEmpty) {
    return Uri.file(override);
  }
  if (!Platform.isWindows) {
    return null; // Let ffigen find the system libclang.
  }
  final sdk =
      Platform.environment['ANDROID_HOME'] ??
      Platform.environment['ANDROID_SDK_ROOT'] ??
      '${Platform.environment['LOCALAPPDATA']}\\Android\\Sdk';
  return Uri.file(
    '$sdk\\ndk\\$_ndkVersion\\toolchains\\llvm\\prebuilt\\windows-x86_64'
    r'\bin\libclang.dll',
  );
}
