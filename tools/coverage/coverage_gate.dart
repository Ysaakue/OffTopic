// Dart coverage gate for the workspace.
//
//   fvm dart run tools/coverage/coverage_gate.dart prepare
//       Writes test/coverage_imports_test.dart in every package. It imports
//       every library, so a file that no test touches still shows up in
//       lcov.info (as uncovered) instead of silently disappearing.
//   fvm dart run tools/coverage/coverage_gate.dart check
//       Reads <package>/coverage/lcov.info and enforces the thresholds below.
//   fvm dart run tools/coverage/coverage_gate.dart clean
//       Deletes the generated import tests.
//
// The thresholds and the closed exclusion list mirror docs/IMPLEMENTATION_PLAN.md
// ("Testes unitários: cobertura máxima"). They may only go up.
import 'dart:io';

/// Packages of the workspace, relative to the repository root.
const _packages = ['app', 'packages/voice_core', 'packages/voice_platform'];

/// Files outside the gate (closed list; see CLAUDE.md).
final _excluded = [
  RegExp(r'\.g\.dart$'),
  RegExp('^lib/l10n/generated/'),
  RegExp(r'^lib/main\.dart$'),
];

/// Areas that must be fully covered: pure logic with no excuse for gaps.
final _strictAreas = <String, List<RegExp>>{
  'app': [
    RegExp('^lib/core/result/'),
    RegExp('^lib/features/[^/]+/domain/'),
    RegExp('^lib/features/[^/]+/data/'),
    RegExp('^lib/features/[^/]+/presentation/controllers/'),
  ],
  'packages/voice_core': [RegExp('^lib/src/')],
  'packages/voice_platform': [RegExp('^lib/src/')],
};

const _strictThreshold = 100.0;
const _overallThreshold = 95.0;
const _importsTest = 'test/coverage_imports_test.dart';

Future<void> main(List<String> arguments) async {
  final root = Directory.fromUri(Platform.script.resolve('../../'));
  final command = arguments.isEmpty ? 'check' : arguments.first;
  switch (command) {
    case 'prepare':
      _prepare(root);
    case 'clean':
      _clean(root);
    case 'check':
      exitCode = _check(root) ? 0 : 1;
    default:
      stderr.writeln(
        'Unknown command "$command". Use prepare, check or clean.',
      );
      exitCode = 64;
  }
}

void _prepare(Directory root) {
  for (final package in _packages) {
    final packageDir = Directory('${root.path}$package');
    final name = _packageName(packageDir);
    final libraries = _libraries(packageDir)
        .where((path) => !_isExcluded(path))
        .map((path) => "import 'package:$name/${path.substring(4)}';")
        .toList();
    File('${packageDir.path}/$_importsTest').writeAsStringSync(
      [
        '// GENERATED by tools/coverage/coverage_gate.dart. Do not commit.',
        '// Loads every library so untested files count as uncovered.',
        '// ignore_for_file: type=lint',
        "import 'package:flutter_test/flutter_test.dart';",
        ...libraries,
        '',
        "void main() => test('every library loads', () {});",
        '',
      ].join('\n'),
    );
    stdout.writeln('prepared $package (${libraries.length} libraries)');
  }
}

void _clean(Directory root) {
  for (final package in _packages) {
    final file = File('${root.path}$package/$_importsTest');
    if (file.existsSync()) {
      file.deleteSync();
    }
  }
}

bool _check(Directory root) {
  var passed = true;
  var totalFound = 0;
  var totalHit = 0;

  for (final package in _packages) {
    final lcov = File('${root.path}$package/coverage/lcov.info');
    if (!lcov.existsSync()) {
      stderr.writeln(
        '$package: coverage/lcov.info not found. Run tests with '
        '--coverage first.',
      );
      passed = false;
      continue;
    }
    final files = _parseLcov(lcov).where((file) => !_isExcluded(file.path));
    for (final file in files) {
      totalFound += file.found;
      totalHit += file.hit;
      final strict = (_strictAreas[package] ?? const <RegExp>[]).any(
        (area) => area.hasMatch(file.path),
      );
      if (strict && file.percent < _strictThreshold) {
        passed = false;
        stderr.writeln(
          'FAIL $package/${file.path}: ${_format(file.percent)} '
          '(strict area needs ${_format(_strictThreshold)}; uncovered lines: '
          '${file.uncoveredLines.join(', ')})',
        );
      }
    }
  }

  final overall = totalFound == 0 ? 100.0 : totalHit * 100 / totalFound;
  final overallOk = overall >= _overallThreshold;
  passed = passed && overallOk;
  stdout
    ..writeln(
      '${overallOk ? 'OK  ' : 'FAIL'} overall Dart line coverage: '
      '${_format(overall)} ($totalHit/$totalFound, needs '
      '${_format(_overallThreshold)})',
    )
    ..writeln(
      passed ? 'Dart coverage gate passed.' : 'Dart coverage gate FAILED.',
    );
  return passed;
}

String _format(double percent) => '${percent.toStringAsFixed(1)}%';

String _packageName(Directory packageDir) {
  final pubspec = File('${packageDir.path}/pubspec.yaml').readAsLinesSync();
  return pubspec
      .firstWhere((line) => line.startsWith('name:'))
      .substring('name:'.length)
      .trim();
}

Iterable<String> _libraries(Directory packageDir) {
  final lib = Directory('${packageDir.path}/lib');
  final prefix = '${packageDir.path}/';
  return lib
      .listSync(recursive: true)
      .whereType<File>()
      .where((file) => file.path.endsWith('.dart'))
      .map((file) => _normalize(file.path).replaceFirst(_normalize(prefix), ''))
      .toList()
    ..sort();
}

bool _isExcluded(String path) => _excluded.any((rule) => rule.hasMatch(path));

String _normalize(String path) => path.replaceAll(r'\', '/');

final class _FileCoverage {
  new(this.path);

  final String path;
  final Map<int, int> hitsByLine = {};

  int get found => hitsByLine.length;

  int get hit => hitsByLine.values.where((hits) => hits > 0).length;

  double get percent => found == 0 ? 100 : hit * 100 / found;

  List<int> get uncoveredLines =>
      hitsByLine.entries.where((e) => e.value == 0).map((e) => e.key).toList()
        ..sort();
}

List<_FileCoverage> _parseLcov(File lcov) {
  final files = <_FileCoverage>[];
  _FileCoverage? current;
  for (final line in lcov.readAsLinesSync()) {
    if (line.startsWith('SF:')) {
      final path = _normalize(line.substring(3));
      final libIndex = path.indexOf('lib/');
      current = _FileCoverage(libIndex < 0 ? path : path.substring(libIndex));
      files.add(current);
    } else if (line.startsWith('DA:') && current != null) {
      final parts = line.substring(3).split(',');
      current.hitsByLine[int.parse(parts[0])] = int.parse(parts[1]);
    }
  }
  return files;
}
